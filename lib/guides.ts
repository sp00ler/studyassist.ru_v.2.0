// Informational guides for /gid. Content is plain data so the page component
// stays generic. Paragraph text inside `sample` blocks may contain "\n\n"
// (rendered as separate paragraphs).

export type GuideBlock =
  | { type: 'p'; text: string }
  | { type: 'ul'; items: string[] }
  | { type: 'ol'; items: string[] }
  | { type: 'table'; head: string[]; rows: string[][] }
  | { type: 'sample'; title: string; text: string }

export interface GuideSection {
  id: string
  h2: string
  blocks: GuideBlock[]
}

export interface GuideFAQ { q: string; a: string }

export interface GuideCta {
  title: string
  text: string
  href: string
  label: string
}

export interface Guide {
  slug: string
  /** Full <title>, brand suffix included (the root layout template is a no-op). */
  title: string
  description: string
  h1: string
  /** Short name for the breadcrumb and "read also" links. */
  shortName: string
  /** ISO date, also shown as «Обновлено дд.мм.гггг». */
  updated: string
  lead: string
  toc: { id: string; label: string }[]
  sections: GuideSection[]
  /** Soft CTA rendered after this section id (the second one always closes the page). */
  midCta: GuideCta & { afterSection: string }
  endCta: GuideCta
  faq: GuideFAQ[]
  download?: { href: string; label: string }
  relatedSlug: string
}

function defineGuide(g: Omit<Guide, 'toc'>): Guide {
  return { ...g, toc: g.sections.map((s) => ({ id: s.id, label: s.h2 })) }
}

